using VRCX.Vrchat;

namespace VRCX.Common.Tests;

// The upload signature must be byte for byte what the original's librsync.net made; these are its
// outputs for the same inputs.
public class RsyncSignatureTests
{
    private static byte[] Input(int length) => Enumerable.Range(0, length).Select(i => (byte)((i * 7 + 3) % 251)).ToArray();

    [Test]
    [Arguments(0, "727301370000080000000020")]
    [Arguments(1, "72730137000008000000002000220022E88BD757AD5B9BEDF372D8D3F0CF6C962A469DB61A265F6418E1FFED86DA29EC")]
    [Arguments(2048, "7273013700000800000000203CD6DE58B5F583B4CC17149AE584BE893A2A9C36F590C64374AED88931AC9B404CC2E3C7")]
    [Arguments(2049, "7273013700000800000000203CD6DE58B5F583B4CC17149AE584BE893A2A9C36F590C64374AED88931AC9B404CC2E3C7003F003FAE85D245A3D00BFDE01F59F3C4FE0B4BFAE1CB37E9CF91929EADCEA4985711DE")]
    [Arguments(5000, "7273013700000800000000203CD6DE58B5F583B4CC17149AE584BE893A2A9C36F590C64374AED88931AC9B404CC2E3C77DFCDEF4FCE71C4FCD24999F501E492F817555334510C50547E28208591648F4D672A61FF3F6253E53A1F358E1C228DC8000BD6C45491E94775BF772ABDA03E7787BF8261862AAF2")]
    public async Task Signature_matches_librsync_net(int length, string expected)
    {
        await Assert.That(Convert.ToHexString(RsyncSignature.Compute(Input(length)))).IsEqualTo(expected);
    }
}
